import type { ClipboardBookmark } from "electron";

/**
 * Password managers mark what they put on the clipboard so that clipboard managers and history skip it.
 * Inset Shelf honours the marks: a clipboard marked so is neither read nor rewritten, and a selection
 * copied with the marks is not captured.
 * macOS: nspasteboard.org's types. Windows: Microsoft's clipboard-history and cloud-clipboard formats
 * and the older "Clipboard Viewer Ignore".
 */

/** Present means "do not record this" (macOS and Windows). */
const MARKS = [
  "org.nspasteboard.ConcealedType",
  "org.nspasteboard.TransientType",
  "org.nspasteboard.AutoGeneratedType",
  "ExcludeClipboardContentFromMonitorProcessing",
  "Clipboard Viewer Ignore",
] as const;

/** Present with the value 0 means "do not record this" (Windows, a DWORD). */
const ZERO_MARKS = [
  "CanIncludeInClipboardHistory",
  "CanUploadToCloudClipboard",
] as const;

/** How Electron names a platform format it has no mime type for. */
const RAW = /^electron application\/osclipboard;format="(?<format>.*)"$/u;

const bare = (format: string): string =>
  RAW.exec(format)?.groups?.format ?? format;

/** The name Electron's clipboard reports a platform format under. */
export const rawFormat = (format: string): string =>
  `electron application/osclipboard;format="${format}"`;

/** The formats whose value, not only their presence, says whether the clipboard is private. */
export const VALUE_MARKS: readonly string[] = ZERO_MARKS;

const isZero = (value: Buffer): boolean => value.every((byte) => byte === 0);

/**
 * Whether a clipboard holding `formats` is marked as private. Formats may be named bare or as Electron
 * names raw ones. `read` gives a format's bytes for the Windows marks that count only with the value 0;
 * without it (or when it fails) such a mark counts as private, which skips rather than records.
 */
export const isConcealedClipboard = (
  formats: readonly string[],
  read?: (format: string) => Buffer
): boolean => {
  const names = new Set(formats.map((format) => bare(format).toLowerCase()));

  if (MARKS.some((mark) => names.has(mark.toLowerCase()))) {
    return true;
  }

  return ZERO_MARKS.some((mark) => {
    if (!names.has(mark.toLowerCase())) {
      return false;
    }

    try {
      return read === undefined ? true : isZero(read(mark));
    } catch {
      return true;
    }
  });
};

/** What `clipboard.read()` returns for each item, as far as the marks go. */
export interface MarkedItem {
  readonly types: readonly string[];
  readonly getType: (type: string) => Promise<Blob | ClipboardBookmark>;
}

/** Whether any item of a clipboard read is marked private. Reads only the values of the Windows 0/1 marks. */
export const itemsConcealed = async (
  items: readonly MarkedItem[]
): Promise<boolean> => {
  const formats = items.flatMap((item) => item.types);

  const values = new Map<string, Buffer>();

  await Promise.all(
    items.flatMap((item) =>
      item.types.flatMap((type) => {
        const name = VALUE_MARKS.find(
          (mark) => mark.toLowerCase() === bare(type).toLowerCase()
        );

        return name === undefined
          ? []
          : [
              (async () => {
                try {
                  const blob = await item.getType(type);

                  if (blob instanceof Blob) {
                    values.set(name, Buffer.from(await blob.arrayBuffer()));
                  }
                } catch {
                  // Unreadable: counts as private.
                }
              })(),
            ];
      })
    )
  );

  return isConcealedClipboard(formats, (format) => {
    const value = values.get(format);

    if (value === undefined) {
      throw new Error("unread");
    }

    return value;
  });
};

export type ConcealedHit = "original" | "selection";

/**
 * Follows one Double Shift capture: whether the clipboard it started with was private (left alone, nothing
 * copied) or the selection it copied was (not captured).
 */
export interface SelectionGuard {
  readonly begin: () => void;
  /** The clipboard was cleared for the copy: marks seen from now on belong to the selection. */
  readonly cleared: () => void;
  /** A private clipboard was seen. */
  readonly note: () => void;
  readonly hit: () => ConcealedHit | null;
}

export const createSelectionGuard = (): SelectionGuard => {
  let afterClear = false;
  let found: ConcealedHit | null = null;

  return {
    begin: () => {
      afterClear = false;
      found = null;
    },
    cleared: () => {
      afterClear = true;
    },
    hit: () => found,
    note: () => {
      found ??= afterClear ? "selection" : "original";
    },
  };
};
