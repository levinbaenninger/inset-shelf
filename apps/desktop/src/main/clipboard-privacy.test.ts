import { describe, expect, it } from "vite-plus/test";

import {
  isConcealedClipboard,
  itemsConcealed,
  rawFormat,
} from "./clipboard-privacy";

const DWORD = (value: number): Buffer => {
  const buffer = Buffer.alloc(4);

  buffer.writeUInt32LE(value);

  return buffer;
};

describe(isConcealedClipboard, () => {
  it.each([
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "ExcludeClipboardContentFromMonitorProcessing",
    "Clipboard Viewer Ignore",
  ])("treats %s as private, bare or as Electron names it", (mark) => {
    expect(isConcealedClipboard(["text/plain", mark])).toBeTruthy();
    expect(isConcealedClipboard(["text/plain", rawFormat(mark)])).toBeTruthy();
  });

  it("ignores ordinary clipboards", () => {
    expect(isConcealedClipboard([])).toBeFalsy();
    expect(
      isConcealedClipboard(["text/plain", "text/html", "image/png"])
    ).toBeFalsy();
  });

  it.each(["CanIncludeInClipboardHistory", "CanUploadToCloudClipboard"])(
    "treats %s as private only with the value 0",
    (mark) => {
      expect(
        isConcealedClipboard([rawFormat(mark)], () => DWORD(0))
      ).toBeTruthy();
      expect(
        isConcealedClipboard([rawFormat(mark)], () => DWORD(1))
      ).toBeFalsy();
    }
  );

  it("treats a 0/1 mark it can't read as private", () => {
    expect(isConcealedClipboard(["CanIncludeInClipboardHistory"])).toBeTruthy();
    expect(
      isConcealedClipboard(["CanIncludeInClipboardHistory"], () => {
        throw new Error("no");
      })
    ).toBeTruthy();
  });
});

const item = (marks: Readonly<Record<string, Buffer>>) => ({
  getType: async (type: string) =>
    await Promise.resolve(new Blob([marks[type] ?? ""])),
  types: Object.keys(marks),
});

describe(itemsConcealed, () => {
  it("reads the value of a Windows 0/1 mark", async () => {
    const history = rawFormat("CanIncludeInClipboardHistory");

    await expect(
      itemsConcealed([item({ [history]: DWORD(0) })])
    ).resolves.toBeTruthy();
    await expect(
      itemsConcealed([item({ [history]: DWORD(1) })])
    ).resolves.toBeFalsy();
  });

  it("finds a mark on any item", async () => {
    await expect(
      itemsConcealed([
        item({ "text/plain": Buffer.from("a") }),
        item({
          [rawFormat("org.nspasteboard.ConcealedType")]: Buffer.from(""),
        }),
      ])
    ).resolves.toBeTruthy();
    await expect(
      itemsConcealed([item({ "text/plain": Buffer.from("a") })])
    ).resolves.toBeFalsy();
  });
});

describe("expander marks", () => {
  it("does not treat AutoGeneratedType as private", () => {
    expect(
      isConcealedClipboard(["text/plain", "org.nspasteboard.AutoGeneratedType"])
    ).toBeFalsy();
  });
});
